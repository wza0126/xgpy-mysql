-- 知识点讲解 · 老师指定的「讲解重点」（2026-11-01）
--
-- 背景：同一节讲义，不同老师想突出的点不一样。例如「运算符与表达式」这一节，
-- 讲义把 7 个算术运算符 + 5 个关系运算符 + 3 个逻辑运算符 + 优先级全列了一遍，
-- 平均用力讲下来每个都只有一两句；而实际上学测主要考 // % ** 和关系运算符。
--
-- 做法：允许老师给某节指定「本次讲解重点」，生成时按重点重新分配篇幅
--       （重点各自独立成要点展开，其余合并带过）。
--
-- ⛔ 这一列是**这一节的长期设置**，不是某次生成的临时参数：
--    学生端生成时也会自动带上它，保证全校听到的是同一份口径；
--    否则老师定制一份、学生一端生成就被覆盖了。
-- ⛔ 为空 = 没有定制，走通用的「按讲义结构平均拆」。
ALTER TABLE `knowledge_explain_scripts`
  ADD COLUMN IF NOT EXISTS `focus` TEXT DEFAULT NULL COMMENT '老师指定的讲解重点（为空表示未定制）' AFTER `model`;
