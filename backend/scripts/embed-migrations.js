const fs = require('fs/promises');
const path = require('path');

const migrationsDir = path.resolve(__dirname, '../database/migrations');
const outputFile = path.resolve(__dirname, '../src/embedded-migrations.js');

async function main() {
  const entries = await fs.readdir(migrationsDir, { withFileTypes: true });
  const migrations = [];

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.sql')) continue;
    const sql = await fs.readFile(path.join(migrationsDir, entry.name), 'utf8');
    migrations.push({ version: entry.name, sql });
  }

  migrations.sort((a, b) => a.version.localeCompare(b.version));

  const source = [
    '// Auto-generated by scripts/embed-migrations.js. Do not edit by hand.',
    `module.exports = ${JSON.stringify(migrations, null, 2)};`,
    '',
  ].join('\n');

  await fs.writeFile(outputFile, source);
  console.log(`Embedded ${migrations.length} migrations into ${path.relative(process.cwd(), outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
