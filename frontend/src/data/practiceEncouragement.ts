/** 再点「开始练习」但这一节已经全掌握时用的开场句（配合上面的剧情一起显示） */
export const ALL_CLEAR_LEADS: string[] = [
  '这一节的题，全在你的「已掌握」里了。',
  '系统翻遍了这一节，没找到一道你还没做会的题。',
  '这一节已经没有可出的题了 —— 因为都被你做会了。',
];

/** 按正确率给一句评语（不吹不贬，承认过程） */
export function cheerComment(correct: number, total: number): string {
  if (total <= 0) return '这一节你已经全部掌握了 —— 去下一节看看。';
  if (correct >= total) return '零失误。这不是运气，是练到了。';
  const rate = correct / total;
  if (rate >= 0.8) return '错了几次，但每次都自己改对了 —— 这比全对更值钱。';
  return '这一节你不是「刷完」的，是「磨会」的。';
}

const LAST_KEY = 'xgpy.practice.cheer.last';

/** 随机取一条，尽量不跟上次重复（同一台机器） */
export function pickCheer(): PracticeCheer {
  let last = '';
  try {
    last = window.localStorage.getItem(LAST_KEY) || '';
  } catch {
    /* 隐私模式读不到就算了 */
  }
  const pool = PRACTICE_CHEERS.filter((c) => c.id !== last);
  const list = pool.length ? pool : PRACTICE_CHEERS;
  const picked = list[Math.floor(Math.random() * list.length)];
  try {
    window.localStorage.setItem(LAST_KEY, picked.id);
  } catch {
    /* 同上 */
  }
  return picked;
}

/** 全掌握时的开场句，也做一次不重复 */
export function pickAllClearLead(): string {
  return ALL_CLEAR_LEADS[Math.floor(Math.random() * ALL_CLEAR_LEADS.length)];
}
